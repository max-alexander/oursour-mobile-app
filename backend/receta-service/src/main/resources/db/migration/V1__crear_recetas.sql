CREATE TABLE ingredientes (
    id          NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR2(80) NOT NULL,
    categoria   VARCHAR2(20) NOT NULL
        CHECK (categoria IN ('OUR_SOUR', 'DESTILADO', 'LICOR', 'FRUTA', 'JUGO', 'MIXER', 'OTRO')),
    producto_id NUMBER(19),
    CONSTRAINT uk_ingredientes_nombre UNIQUE (nombre)
);

CREATE TABLE recetas (
    id          NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo      VARCHAR2(120) NOT NULL,
    descripcion VARCHAR2(500),
    sin_alcohol BOOLEAN       DEFAULT FALSE NOT NULL,
    producto_id NUMBER(19),
    CONSTRAINT uk_recetas_titulo UNIQUE (titulo)
);

CREATE TABLE receta_ingredientes (
    id             NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receta_id      NUMBER(19)  NOT NULL REFERENCES recetas (id) ON DELETE CASCADE,
    ingrediente_id NUMBER(19)  NOT NULL REFERENCES ingredientes (id),
    cantidad       VARCHAR2(60),
    CONSTRAINT uk_receta_ingrediente UNIQUE (receta_id, ingrediente_id)
);

CREATE TABLE receta_pasos (
    receta_id   NUMBER(19)    NOT NULL REFERENCES recetas (id) ON DELETE CASCADE,
    orden       NUMBER(10)    NOT NULL,
    descripcion VARCHAR2(500) NOT NULL,
    PRIMARY KEY (receta_id, orden)
);

CREATE TABLE busquedas (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha      TIMESTAMP  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    resultados NUMBER(10) DEFAULT 0 NOT NULL
);

CREATE TABLE busqueda_ingredientes (
    busqueda_id    NUMBER(19) NOT NULL REFERENCES busquedas (id) ON DELETE CASCADE,
    ingrediente_id NUMBER(19) NOT NULL REFERENCES ingredientes (id),
    PRIMARY KEY (busqueda_id, ingrediente_id)
);

CREATE TABLE consultas_receta (
    id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receta_id NUMBER(19) NOT NULL REFERENCES recetas (id) ON DELETE CASCADE,
    fecha     TIMESTAMP  DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_receta_ingredientes_ing ON receta_ingredientes (ingrediente_id);
CREATE INDEX idx_consultas_receta_receta ON consultas_receta (receta_id);
