CREATE TABLE carros (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          NUMBER(19) NOT NULL,
    fecha_actualizacion TIMESTAMP  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_carros_usuario UNIQUE (usuario_id)
);

CREATE TABLE carro_items (
    id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carro_id        NUMBER(19)    NOT NULL REFERENCES carros (id) ON DELETE CASCADE,
    producto_id     NUMBER(19)    NOT NULL,
    nombre_producto VARCHAR2(120) NOT NULL,
    precio_unitario NUMBER(10)    NOT NULL,
    cantidad        NUMBER(10)    NOT NULL CHECK (cantidad > 0),
    CONSTRAINT uk_carro_producto UNIQUE (carro_id, producto_id)
);

CREATE TABLE pedidos (
    id                  NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          NUMBER(19)    NOT NULL,
    estado              VARCHAR2(20)  DEFAULT 'SOLICITADO' NOT NULL
        CHECK (estado IN ('SOLICITADO', 'EN_PREPARACION', 'DESPACHADO', 'ENTREGADO')),
    subtotal            NUMBER(10)    NOT NULL,
    costo_despacho      NUMBER(10)    NOT NULL,
    total               NUMBER(10)    NOT NULL,
    despacho_calle      VARCHAR2(150) NOT NULL,
    despacho_numero     VARCHAR2(20)  NOT NULL,
    despacho_comuna     VARCHAR2(80)  NOT NULL,
    despacho_ciudad     VARCHAR2(80)  NOT NULL,
    despacho_referencia VARCHAR2(200),
    codigo_pago         VARCHAR2(40)  NOT NULL,
    fecha               TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE pedido_items (
    id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       NUMBER(19)    NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    producto_id     NUMBER(19)    NOT NULL,
    nombre_producto VARCHAR2(120) NOT NULL,
    precio_unitario NUMBER(10)    NOT NULL,
    cantidad        NUMBER(10)    NOT NULL,
    subtotal        NUMBER(10)    NOT NULL
);

CREATE INDEX idx_pedidos_usuario ON pedidos (usuario_id);
CREATE INDEX idx_pedido_items_pedido ON pedido_items (pedido_id);
