CREATE TABLE usuarios (
    id             NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR2(100) NOT NULL,
    email          VARCHAR2(150) NOT NULL,
    password       VARCHAR2(100) NOT NULL,
    rol            VARCHAR2(20)  DEFAULT 'CLIENTE' NOT NULL CHECK (rol IN ('CLIENTE', 'ADMIN')),
    fecha_registro TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE direcciones (
    id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id NUMBER(19)    NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    calle      VARCHAR2(150) NOT NULL,
    numero     VARCHAR2(20)  NOT NULL,
    comuna     VARCHAR2(80)  NOT NULL,
    ciudad     VARCHAR2(80)  NOT NULL,
    referencia VARCHAR2(200)
);

CREATE INDEX idx_direcciones_usuario ON direcciones (usuario_id);
